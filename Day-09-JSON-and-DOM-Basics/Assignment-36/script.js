
// 1. Select element by ID
let heading = document.getElementById("heading");
console.log(heading);

// 2. Select first element by class name
let info = document.querySelector(".info");
console.log(info);

// 3. Select all elements by class name
let allInfo = document.querySelectorAll(".info");
console.log(allInfo);

// 4. Select element using tag name
let paragraphs = document.getElementsByTagName("p");
console.log(paragraphs);

// 5. Select all list items
let subjects = document.querySelectorAll("li");
console.log(subjects);

// 6. Select button
let button = document.querySelector("button");
console.log(button);
