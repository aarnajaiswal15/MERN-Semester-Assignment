
// Function 1: Addition
function add(a, b) {
    return a + b;
}


// Function 2: Subtraction
function subtract(a, b) {
    return a - b;
}


// Function 3: Multiplication
function multiply(a, b) {
    return a * b;
}


// Function 4: Division
function divide(a, b) {
    if (b === 0) {
        return "Cannot divide by zero";
    }

    return a / b;
}


// Function 5: Square
function square(a) {
    return a * a;
}
